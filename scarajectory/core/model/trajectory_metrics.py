__maintainer__: str = 'Vladimir Roncevic'
__email__ = 'elektron.ronca@gmail.com'
__status__ = 'Updated'


class TrajectoryMetrics:
    '''
        Computes motion distance, duration, and serializes trajectory plans.

        It defines:

            :methods:
                | calculate_distance - Computes total 3D Cartesian distance along the path.
                | calculate_duration - Computes estimated execution duration based on speeds.
                | to_ascii_program - Generates full sequential ASCII firmware instruction stream.
                | save_json - Saves waypoints sequence to JSON file.
                | load_json - Loads waypoints sequence from JSON file.
    '''

    @staticmethod
    def calculate_distance(waypoints: Sequence[StudioWaypoint]) -> float:
        '''
            Computes total 3D Cartesian distance along the path in mm.

            :param waypoints: Sequence of waypoints.
            :return: Cumulative distance in mm.
            :exceptions: None.
        '''
        if len(waypoints) < 2:
            return 0.0
        total: float = 0.0
        for i in range(len(waypoints) - 1):
            total += waypoints[i].distance_to(waypoints[i + 1])
        return total

    @staticmethod
    def calculate_duration(waypoints: Sequence[StudioWaypoint]) -> float:
        '''
            Computes estimated execution duration based on waypoint speeds in seconds.

            :param waypoints: Sequence of waypoints.
            :return: Estimated duration in seconds.
            :exceptions: None.
        '''
        if len(waypoints) < 2:
            return 0.0
        total_sec: float = 0.0
        for i in range(len(waypoints) - 1):
            dist: float = waypoints[i].distance_to(waypoints[i + 1])
            spd: float = max(1.0, waypoints[i + 1].speed)
            total_sec += dist / spd
        return total_sec

    @classmethod
    def to_ascii_program(cls, waypoints: Sequence[StudioWaypoint]) -> str:
        '''
            Generates full sequential ASCII firmware instruction stream.

            :param waypoints: Sequence of waypoints.
            :return: Multi-line ASCII packet program.
            :exceptions: None.
        '''
        total_dist: float = cls.calculate_distance(waypoints)
        lines: list[str] = [
            '; --- SCARA Motion Program Generated by SCARAjectory ---',
            f'; Total Waypoints: {len(waypoints)}',
            f'; Total Distance: {total_dist:.2f} mm',
            '<CMD:ENABLE>'
        ]
        for pt in waypoints:
            lines.append(pt.to_ascii_packet())
        return '\n'.join(lines)

    @staticmethod
    def save_json(waypoints: Sequence[StudioWaypoint], filepath: str) -> None:
        '''
            Saves waypoints sequence to JSON file.

            :param waypoints: Sequence of waypoints.
            :param filepath: Target destination file path.
            :exceptions: OSError, json.JSONDecodeError.
        '''
        data: dict[str, object] = {
            'version': '1.0.0',
            'waypoints': [pt.to_dict() for pt in waypoints]
        }
        with open(filepath, 'w', encoding='utf-8') as file_handle:
            json.dump(data, file_handle, indent=2)

    @staticmethod
    def load_json(filepath: str) -> list[StudioWaypoint]:
        '''
            Loads waypoints sequence from JSON file.

            :param filepath: Source file path.
            :return: List of loaded StudioWaypoint instances.
            :exceptions: OSError, json.JSONDecodeError.
        '''
        with open(filepath, 'r', encoding='utf-8') as file_handle:
            data: dict[str, object] = json.load(file_handle)
        loaded_pts: list[StudioWaypoint] = []
        raw_list = data.get('waypoints', [])
        if isinstance(raw_list, list):
            for item in raw_list:
                if isinstance(item, dict):
                    loaded_pts.append(StudioWaypoint.from_dict(item))
        return loaded_pts
