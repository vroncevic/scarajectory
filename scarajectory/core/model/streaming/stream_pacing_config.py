@dataclass(frozen=True, slots=True, kw_only=True)
class StreamPacingConfig:
    '''
        Data model encapsulating pacing and throttling delay parameters for streaming execution.

        It defines:

            :attributes:
                | send_delay - Loop pacing delay after transmitting packet in seconds.
                | throttle_delay - Delay when buffer queue is full in seconds.
                | poll_delay - Polling interval during pause or completion wait in seconds.
    '''

    send_delay: float
    throttle_delay: float
    poll_delay: float
